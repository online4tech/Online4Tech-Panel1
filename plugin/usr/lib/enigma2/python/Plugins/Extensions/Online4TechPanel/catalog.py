# -*- coding: utf-8 -*-
"""Online4Tech catalog (schema 2): plugins and skins grouped by category.

catalog.json is generated by tools/build_catalog.py from the Online4Tech JSON
databases and published on GitHub; a copy ships inside the plugin for offline use.
"""
from __future__ import absolute_import
import io
import json
import os

from .utils import log, safe_cmd, short_id, safe_remove, txt, valid_pkg, valid_url, cmd_hosts, TRUSTED_HOSTS
from .version import PLUGIN_DIR, CATALOG_URL, TMP_CATALOG

BUNDLED = os.path.join(PLUGIN_DIR, "data", "catalog.json")

ORDER = {
    "plugin": ["Panels", "Plugins", "Media", "IPTV", "Audio", "EPG", "Tools", "System", "Settings",
               "Translation", "Ciefp", "Novaler", "Multiboot", "Dependencies", "Community"],
    "channels": ["Online4Tech & Others", "Ciefp", "Morph883", "Vaninbal"],
    "skin": ["OpenATV", "OpenBH", "Egami", "OpenPLi Py3", "OpenPLi Py2", "OpenSPA", "OpenVIX",
             "PurE2", "TeamNitro", "Display (LCD)", "XStreamity", "Community Skins",
             "Bootlogos", "Spinners", "Picons"],
}


def _load(path):
    try:
        with io.open(path, "r", encoding="utf-8") as fh:
            data = json.load(fh)
        if isinstance(data, dict) and data.get("schema") == 2 and isinstance(data.get("items"), list):
            return data
    except Exception as exc:
        if os.path.exists(path):
            log("catalog load failed %s: %s" % (path, exc))
    return None


def _clean(raw):
    """Validate one entry. Anything unsafe or malformed is dropped (returns None)."""
    try:
        it = {"type": txt(raw.get("type")), "category": txt(raw.get("category", "")),
              "name": txt(raw.get("name", "")).strip(), "method": txt(raw.get("method")),
              "desc": txt(raw.get("desc", "")), "version": txt(raw.get("version", "")), "added": txt(raw.get("added", "")),
              "cmd": txt(raw.get("cmd", "")), "url": txt(raw.get("url", "")),
              "pkg": txt(raw.get("pkg", "")), "path": txt(raw.get("path", "")),
              "remove": txt(raw.get("remove", "")),
              "images": [txt(x) for x in raw.get("images", []) if x][:6]}
        if not it["name"] or not it["category"] or it["type"] not in ("plugin", "skin", "channels"):
            return None
        m = it["method"]
        if m == "cmd":
            if not safe_cmd(it["cmd"]):
                return None
        elif m == "ipk":
            if not valid_url(it["url"]) or not cmd_hosts(it["url"]) <= TRUSTED_HOSTS:
                return None
        elif m == "feed":
            if not valid_pkg(it["pkg"]):
                return None
        else:
            return None
        if it["path"] and not it["path"].startswith("/"):
            it["path"] = ""
        if it["remove"] and not safe_remove(it["remove"]):
            it["remove"] = ""
        _keep_py(raw, it)
        it["id"] = short_id("%s|%s|%s" % (it["type"], it["category"], it["name"]))
        return it
    except Exception:
        return None


def info():
    """(source, updated, total_items)"""
    data = _load(TMP_CATALOG)
    src = "GitHub (synced)"
    if not data:
        data, src = _load(BUNDLED) or {"items": []}, "built-in"
    return src, data.get("updated", "-"), len(data["items"])


def _keep_py(raw, it):
    if raw.get("py") in ("py2", "py3"):
        it["py"] = raw["py"]


_ALL = {"key": None, "items": []}


def _stamp(path):
    try:
        st = os.stat(path)
        return (path, st.st_mtime, st.st_size)
    except OSError:
        return (path, 0, 0)


def _all():
    """Every valid catalog item. The JSON is read and cleaned once and re-read only when a file changes
    (this used to happen on every category switch, which made the store feel slow)."""
    key = (_stamp(TMP_CATALOG), _stamp(BUNDLED))
    if _ALL["key"] != key:
        data = _load(TMP_CATALOG) or _load(BUNDLED) or {"items": []}
        out = []
        for raw in data["items"]:
            it = _clean(raw)
            if it:
                out.append(it)
        _ALL["key"], _ALL["items"] = key, out
    return _ALL["items"]


def items(kind):
    return [i for i in _all() if i["type"] == kind]


ADDED_BASELINE = "2026-01-01"      # items that existed before 'added' dates were tracked


def latest(limit=40, keep=None):
    """Newest catalog additions (plugins, skins, tools...), newest first."""
    pool = []
    for kind in ("plugin", "skin"):
        pool += items(kind)
    if keep:
        pool = [i for i in pool if keep(i)]
    pool = [i for i in pool if i.get("added", "") > ADDED_BASELINE]
    pool.sort(key=lambda i: i["added"], reverse=True)       # stable: ties keep catalog order
    return pool[:limit]


def categories(kind, all_items=None):
    """[(category, count)] in a sensible order."""
    counts = {}
    for it in (all_items if all_items is not None else items(kind)):
        counts[it["category"]] = counts.get(it["category"], 0) + 1
    order = [c for c in ORDER.get(kind, []) if c in counts]
    order += sorted(c for c in counts if c not in order)
    return [(c, counts[c]) for c in order]


def refresh(console, callback):
    """Download catalog.json from GitHub (non-blocking). callback(ok: bool)."""
    cmd = ("wget -q -T 15 -t 1 --no-check-certificate -O %s.part '%s' && "
           "mv -f %s.part %s" % (TMP_CATALOG, CATALOG_URL, TMP_CATALOG, TMP_CATALOG))

    def done(data, retval, extra=None):
        if getattr(console, "_o4t_dead", False):
            return
        _ALL["key"] = None
        ok = (retval == 0) and _load(TMP_CATALOG) is not None
        if not ok:
            for p in (TMP_CATALOG, TMP_CATALOG + ".part"):
                try:
                    os.remove(p)
                except Exception:
                    pass
        callback(ok)

    console.ePopen(cmd, done)


def install_cmd(it):
    """Shell command that installs a catalog item (None when not installable)."""
    from .utils import shquote
    m = it.get("method")
    if m == "cmd":
        return it["cmd"]
    if m == "feed" and valid_pkg(it.get("pkg", "")):
        return "opkg install %s" % shquote(it["pkg"])
    if m == "ipk" and valid_url(it.get("url", "")):
        return ("wget -q --no-check-certificate -O /tmp/o4t_pkg.ipk %s && opkg install "
                "--force-reinstall --force-overwrite /tmp/o4t_pkg.ipk; rm -f /tmp/o4t_pkg.ipk"
                % shquote(it["url"]))
    return None


def remove_cmd(it):
    from .utils import shquote
    if it.get("remove"):
        return it["remove"]
    if it.get("method") == "feed" and valid_pkg(it.get("pkg", "")):
        return "opkg remove %s" % shquote(it["pkg"])
    return None
